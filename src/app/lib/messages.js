/**
 * Returns a single random message object from the given category.
 * @param {keyof typeof MESSAGES} category
 * @returns {{ text: string, emoji: string }}
 */
export function getRandom(category) {
  const pool = MESSAGES[category];
  if (!pool || pool.length === 0) {
    throw new Error(`[mu3alem] Unknown message category: "${category}"`);
  }
  return pool[Math.floor(Math.random() * pool.length)];
}